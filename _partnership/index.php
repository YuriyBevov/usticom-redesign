<script>
	const tabs = document.querySelectorAll('.partnership-tabs__header-item');

	if(tabs.length ) {
		tabs.forEach(tab => {
			tab.addEventListener('click', () => {
				tabs.forEach(tab => {
					tab.classList.remove('active');
				});

				tab.classList.add('active');
				const id = tab.dataset.id;
				const sections = document.querySelectorAll('.partnership-tabs__content-section');

				if(sections.length) {
					sections.forEach(section => {
						section.classList.remove('active');
					});

					sections[id].classList.add('active');
				}
			})
		})
	}

</script>

